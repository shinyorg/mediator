using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace Shiny.Mediator.SourceGenerators;


/// <summary>
/// Emits a reflection-free IContractKeySource (opt-in via ShinyMediatorGenerateContractKeys). Keys use the same
/// format as DefaultContractKeyProvider's reflection fallback - full type name followed by _Prop_value for every
/// non-null public readable property ordered by name - so cache/offline entries stored before enabling it stay valid.
/// Contracts that can't be keyed statically (generic, abstract, inaccessible, indexers, non-public getters) are
/// skipped and fall through to the next key strategy at runtime.
/// </summary>
static class MediatorContractKeySourceGenerator
{
    static readonly string[] ContractInterfaces = ["IRequest", "IStreamRequest", "ICommand", "IEvent"];


    public static bool IsContract(ITypeSymbol type) => type.AllInterfaces.Any(i =>
        i.ContainingNamespace?.ToDisplayString() == "Shiny.Mediator" &&
        ContractInterfaces.Contains(i.Name)
    );


    /// <summary>
    /// Returns true when source was emitted (and the registry should register it).
    /// </summary>
    public static bool Generate(
        SourceProductionContext context,
        Compilation compilation,
        IEnumerable<ITypeSymbol> contractTypes,
        string namespaceName,
        string className
    )
    {
        var contracts = contractTypes
            .OfType<INamedTypeSymbol>()
            .Distinct<INamedTypeSymbol>(SymbolEqualityComparer.Default)
            .Select(x => (Type: x, Properties: GetKeyProperties(compilation, x)))
            .Where(x => x.Properties != null)
            .OrderBy(x => GetClrFullName(x.Type), StringComparer.Ordinal)
            .ToList();

        if (contracts.Count == 0)
            return false;

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine("// Code generated by Shiny Mediator Source Generator.");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine("#nullable disable");
        sb.AppendLine();
        sb.AppendLine($"namespace {namespaceName};");
        sb.AppendLine();
        sb.AppendLine(Constants.GeneratedCodeAttributeString);
        sb.AppendLine($"internal sealed class {className} : global::Shiny.Mediator.Infrastructure.IContractKeySource");
        sb.AppendLine("{");
        sb.AppendLine("    public bool TryGetKey(object contract, out string key)");
        sb.AppendLine("    {");
        sb.AppendLine("        var type = contract.GetType();");

        foreach (var (type, properties) in contracts)
        {
            var typeName = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

            sb.AppendLine();
            sb.AppendLine($"        if (type == typeof({typeName}))");
            sb.AppendLine("        {");
            sb.AppendLine($"            var c = ({typeName})contract;");
            sb.AppendLine($"            key = \"{GetClrFullName(type)}\";");

            foreach (var prop in properties!)
            {
                var append = $"key += $\"_{prop.Name}_{{c.@{prop.Name}}}\";";
                if (IsNonNullableValueType(prop.Type))
                {
                    sb.AppendLine($"            {append}");
                }
                else
                {
                    sb.AppendLine($"            if (c.@{prop.Name} != null)");
                    sb.AppendLine($"                {append}");
                }
            }
            sb.AppendLine("            return true;");
            sb.AppendLine("        }");
        }

        sb.AppendLine();
        sb.AppendLine("        key = null;");
        sb.AppendLine("        return false;");
        sb.AppendLine("    }");
        sb.AppendLine("}");

        context.AddSource($"{namespaceName}.{className}.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
        return true;
    }


    // mirrors Type.GetProperties(Public | Instance).Where(CanRead).OrderBy(Name) - null when the type can't be keyed statically
    static List<IPropertySymbol>? GetKeyProperties(Compilation compilation, INamedTypeSymbol type)
    {
        if (type.IsAbstract || type.IsStatic || type.TypeKind is not (TypeKind.Class or TypeKind.Struct))
            return null;

        if (IsGenericOrNestedInGeneric(type))
            return null;

        if (!compilation.IsSymbolAccessibleWithin(type, compilation.Assembly))
            return null;

        // contracts that supply their own key never reach the generated source
        if (type.AllInterfaces.Any(x => x.ToDisplayString() == "Shiny.Mediator.IContractKey"))
            return null;

        var byName = new Dictionary<string, IPropertySymbol>();
        for (var current = type; current != null && current.SpecialType is not (SpecialType.System_Object or SpecialType.System_ValueType); current = current.BaseType)
        {
            foreach (var prop in current.GetMembers().OfType<IPropertySymbol>())
            {
                if (prop.IsStatic || byName.ContainsKey(prop.Name))
                    continue;

                var isPublic = prop.DeclaredAccessibility == Accessibility.Public ||
                               prop.GetMethod?.DeclaredAccessibility == Accessibility.Public ||
                               prop.SetMethod?.DeclaredAccessibility == Accessibility.Public;
                if (!isPublic)
                    continue;

                // reflection would throw (indexer) or read through an accessor we can't call - leave it to reflection
                if (prop.IsIndexer || prop.ReturnsByRef || prop.ReturnsByRefReadonly || prop.Type.IsRefLikeType || prop.Type.TypeKind == TypeKind.Pointer)
                    return null;

                if (prop.GetMethod == null)
                {
                    byName[prop.Name] = null!; // write-only - not part of the key, but still shadows base members
                    continue;
                }

                if (!compilation.IsSymbolAccessibleWithin(prop.GetMethod, compilation.Assembly))
                    return null;

                byName[prop.Name] = prop;
            }
        }

        return byName
            .Values
            .Where(x => x != null)
            .OrderBy(x => x.Name, StringComparer.InvariantCulture)
            .ToList();
    }


    static bool IsGenericOrNestedInGeneric(INamedTypeSymbol type)
    {
        for (var current = type; current != null; current = current.ContainingType)
        {
            if (current.IsGenericType)
                return true;
        }
        return false;
    }


    static bool IsNonNullableValueType(ITypeSymbol type)
        => type.IsValueType && type.OriginalDefinition.SpecialType != SpecialType.System_Nullable_T;


    // matches System.Type.FullName for non-generic types (nested types joined with '+')
    static string GetClrFullName(INamedTypeSymbol type)
    {
        var name = type.Name;
        for (var parent = type.ContainingType; parent != null; parent = parent.ContainingType)
            name = parent.Name + "+" + name;

        return type.ContainingNamespace is { IsGlobalNamespace: false } ns
            ? ns.ToDisplayString() + "." + name
            : name;
    }
}
